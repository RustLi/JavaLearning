package org.lwl.leetcode;

import java.util.HashMap;
import java.util.Map;

/**
 * LeetCode 560 - 和为 K 的子数组（提交时将类名改为 Solution）
 * <p>
 * 题目：给你一个整数数组 nums 和一个整数 k，请你统计并返回该数组中和为 k 的「子数组」的个数。
 * 子数组是数组中元素的「连续非空」序列。
 * <p>
 * 关键理解：先把题目到底在问什么拆开，否则很容易做错方向。
 * 1. 「子数组」= 连续的一段，不是子序列（子序列可以不连续）。所以答案形如 [i..j] 这样的区间个数。
 * 2. 「连续非空」意味着区间长度至少为 1，即 i <= j；不存在「空区间和为 0」这种凑数的情况。
 * 3. 「和为 k」的 k 可以是 0 或负数，且 nums 中可以含负数、零。
 *    这一条决定了本题两个致命的坑，见下。
 * <p>
 * 坑一：滑动窗口在这里彻底失效，必须放弃这个直觉。
 * 常规的「滑动窗口求子数组和」之所以成立，前提是元素全为非负数——此时窗口内有单调性：
 * 右移右边界和只会变大，左移左边界和只会变小，所以能靠「和太大就缩左边，太小就扩右边」收敛。
 * 一旦出现负数，sum 与窗口长度的单调关系断裂：扩大窗口反而可能让和变小，
 * 于是「缩左边以求变小」的判断彻底不可靠，滑窗会漏解或错解。
 * 本题没有「元素非负」的约束，所以滑窗只能排除，不能用。
 * <p>
 * 坑二：答案可能非常多的原因，往往来自「和为 0 的子段」和重复前缀和。
 * 例如 nums = [1, -1, 0]、k = 0，答案是 3（[1,-1]、[0]、[1,-1,0]），
 * 三个前缀和都等于 0，同一前缀和的「重复出现次数」正是需要被累加的量，
 * 这也解释了为什么哈希表的 value 必须是「次数」而不仅仅是「是否存在」。
 * <p>
 * 核心思路：前缀和 + 哈希表（O(n)）
 * <p>
 * 设 preSum[i] = nums[0] + nums[1] + ... + nums[i]（下标 i 为止的前缀和），并额外定义 preSum[-1] = 0。
 * 那么子数组 [j+1 .. i] 的和 = preSum[i] - preSum[j]。
 * 「和为 k」就等价于：preSum[i] - preSum[j] = k，即 preSum[j] = preSum[i] - k。
 * <p>
 * 于是问题被翻译成：从左到右扫描，固定右端点 i，问「在 i 之前，有多少个位置 j 的前缀和恰好等于 preSum[i] - k」。
 * 「前面出现过哪些前缀和、各出现了几次」这个信息，用一个 HashMap 边走边记即可，
 * 每到一个 i 只需一次 O(1) 查询，就把原本 O(n²) 的枚举全部子数组压缩成了 O(n)。
 * <p>
 * 一个极容易被忽略的细节：哈希表必须预置 {0 : 1}——即「前缀和为 0 的『空前缀』出现 1 次」。
 * 它对应的是 j = -1 这种情况，也就是「子数组从下标 0 开始、一直取到 i」的这一类。
 * 如果漏掉这一项，所有从数组开头算起的、和为 k 的子数组都会被统计丢，是本题最常见的错误。
 * 注意这个 0 是「空前缀」带来的，不是「空子数组」，所以它并不违反「子数组非空」的要求。
 * <p>
 * 关于溢出（工程视角的加固点）：preSum 用 int 累加时，若数组很长且元素很大，理论上可能溢出成负数，
 * 一旦溢出，哈希表的查找会全部落空，结果是静默错误（不抛异常、只是答案错）。
 * LeetCode 本题的数据范围（|nums[i]| <= 1000、长度 <= 2*10^4）离 2^31 很远，用 int 是安全的；
 * 但如果把这段代码搬去处理大数值场景，应把 preSum 与 k 提升为 long（Map 的 key 用 Long），
 * 这是「先判断量级再决定类型」的习惯，而不是无脑用 int。
 * <p>
 * 时间复杂度 O(n)：对 nums 只做一次遍历，每次迭代里哈希表的查询与写入都是均摊 O(1)，故整体线性。
 * 空间复杂度 O(n)：最坏情况下每个位置的前缀和都不同（例如元素互不相同的正数数组），哈希表需要存 n 个键值对。
 * <p>
 * 举一反三：这道题是「前缀和 + 哈希表」这一套路的模板题，值得把它的思维动作固化下来。
 * 1. 「求连续区间的和」→ 先想到前缀和，把区间和转成两个前缀和之差，这是把区间问题降维成点问题的通用手法。
 * 2. 「求和差/差值等于定值的对数」→ 前缀和配上哈希表，把 O(n²) 的两两配对降成 O(n) 的一次扫描。
 *    同款套路见于：LeetCode 1 两数之和（value 存下标）、LeetCode 525 连续数组（把 0 视作 -1 再找和为 0 的最长段）、
 *    LeetCode 1248 统计「优美子数组」（把偶数视作 0、奇数视作 1）、LeetCode 974 和可被 K 整除的子数组（对 K 取模后再计数）。
 *    它们的骨子里都是同一句话：「用哈希表记住之前扫过的状态」。
 * 3. 「哈希表的 value 是次数还是下标，取决于题目问的是『有几条』还是『是哪一条』」。
 *    本题问个数，所以 value 存出现次数；两数之和问具体是哪两个，所以 value 存下标。选错这一项，代码方向就反了。
 * 4. 「负数会摧毁单调性，从而摧毁滑窗、双指针、二分等一切依赖单调的算法」。
 *    拿到题先看有没有「元素非负 / 数组有序」这类前提，它是选解法路线的第一道分水岭。
 * <p>
 * 变体延伸：
 * - 若要求「和 >= k 的子数组个数」：前缀和不再能用普通哈希表直接查，需要配合「离散化 + 树状数组/线段树」做区间计数。
 * - 若要求「最长」而不是「个数」（LeetCode 525）：哈希表 value 改存「该前缀和第一次出现的下标」，
 *   因为要最长，同一个前缀和只保留最早那次即可，后出现的不可能给出更长区间。
 * - 若元素全为非负（题目额外加了约束）：滑窗即可，O(n) 时间、O(1) 空间，比哈希表更省空间，可见约束决定最优解。
 */
public class SubarraySum {

    // ============ 方法一：前缀和 + 哈希表（推荐，O(n) / O(n)） ============

    /**
     * des: 扫描一遍数组，用哈希表记录「每个前缀和出现过几次」，每个位置 O(1) 查出以它结尾有多少个和为 k 的子数组
     *
     * 那么「[j..i] 这个子数组和为 k 」这个条件我们可以转化为
     *
     * pre[i]−pre[j−1]==k
     * 简单移项可得符合条件的下标 j 需要满足
     *
     * pre[j−1]==pre[i]−k
     *
     */
    public int subarraySum(int[] nums, int k) {
        if (nums == null || nums.length == 0) {
            // 没有元素就不存在非空子数组
            return 0;
        }

        // key: 前缀和的值；value: 该前缀和在扫描过程中出现过的次数
        // 容量按元素个数预留，避免中途反复扩容（负载因子 0.75，故取 2n 起步）
        Map<Integer, Integer> preSumCount = new HashMap<>(Math.max(16, nums.length * 2));

        // 关键初始化：空前缀（对应 j = -1）的前缀和为 0，出现 1 次
        // 有了它，"从下标 0 开始"的那一类子数组才能被统计到；漏掉这行是本题最典型的错误
        preSumCount.put(0, 1);

        // preSum 表示当前扫到的位置 i 的前缀和，即 preSum[i]
        int preSum = 0;
        // 满足条件的子数组个数
        int count = 0;

        for (int num : nums) {
            preSum += num;

            // 以当前位置为右端点，需要找此前有多少个前缀和等于 preSum - k
            // 每命中一次，就对应一个 [j+1 .. i] 和为 k 的子数组
            count += preSumCount.getOrDefault(preSum - k, 0);

            // 把当前前缀和登记进哈希表，供它右边的元素查询
            // 注意这里是「先查后写」：顺序反了会把 [i..i] 自身也算进候选，造成错误（k = 0 时尤其明显）
            preSumCount.put(preSum, preSumCount.getOrDefault(preSum, 0) + 1);
        }

        return count;
    }

    public int subarraySum1(int[] nums, int k) {
        int count = 0, pre = 0;
        HashMap < Integer, Integer > mp = new HashMap < > ();
        mp.put(0, 1);
        for (int i = 0; i < nums.length; i++) {
            pre += nums[i];
            if (mp.containsKey(pre - k)) {
                count += mp.get(pre - k);
            }
            mp.put(pre, mp.getOrDefault(pre, 0) + 1);
        }
        return count;
    }

    // ============ 方法二：暴力枚举（O(n²)，用于对照与交叉验证） ============

    /**
     * des: 枚举所有左端点 i，向右累加并实时判断和是否等于 k，命中即计数
     * <p>
     * 时间 O(n²)，空间 O(1)。它没有任何技巧、也就不容易写错，正是它能当好「标尺」的原因：
     * 方法一这类带哈希表优化的写法，最容易在「漏掉空前缀」「先查后写写反了」这些细节上出错，
     * 用暴力解跑同一批用例交叉比对，能立刻暴露问题。
     */
    public int subarraySumByBruteForce(int[] nums, int k) {
        if (nums == null) {
            return 0;
        }

        int count = 0;

        for (int i = 0; i < nums.length; i++) {
            // 固定左端点 i，让右端点 j 从 i 一路向右扩展，sum 即子数组 [i..j] 的和
            int sum = 0;
            for (int j = i; j < nums.length; j++) {
                sum += nums[j];
                // j 从 i 开始，保证子数组非空
                if (sum == k) {
                    count++;
                }
            }
        }

        return count;
    }

    // ============ 测试用例 ============

    public static void main(String[] args) {
        // ---------- 用例 1：官方示例，[1,1,1] 中 2 个和为 2 的子数组 ----------
        check(new int[]{1, 1, 1}, 2, 2);

        // ---------- 用例 2：官方示例，[1,2,3] 中 2 个和为 3 的子数组：{1,2}、{3} ----------
        check(new int[]{1, 2, 3}, 3, 2);

        // ---------- 用例 3：含负数，前缀和回落，验证滑窗失效时哈希表仍正确 ----------
        check(new int[]{1, -1, 0}, 0, 3);

        // ---------- 用例 4：k = 0 且存在重复前缀和，考查「先查后写」的顺序 ----------
        // 若把「登记当前前缀和」提到 count 之前，[i..i] 会被错误计入，答案会偏大
        check(new int[]{0, 0, 0}, 0, 6);

        // ---------- 用例 5：无解，验证计数为 0 ----------
        check(new int[]{1, 2, 3}, 7, 0);

        // ---------- 用例 6：单元素命中 ----------
        check(new int[]{5}, 5, 1);

        // ---------- 用例 7：单元素未命中 ----------
        check(new int[]{5}, 3, 0);

        // ---------- 用例 8：全为负数 ----------
        check(new int[]{-1, -1, -1}, -2, 2);

        // ---------- 用例 9：跨越正负，验证「从下标 0 开始」的子数组能被空前缀统计到 ----------
        check(new int[]{3, 4, 7, 2, -3, 1, 4, 2}, 7, 4);

        // ---------- 用例 10：前缀和大量重复，验证 value 存「次数」而非「是否存在」 ----------
        // 长度为 2 的有 5 个、长度为 4 的有 2 个、长度为 6 的有 1 个，共 9 个
        check(new int[]{1, -1, 1, -1, 1, -1}, 0, 9);

        // ---------- 用例 11：空数组 ----------
        check(new int[]{}, 0, 0);

        // ---------- 用例 12：整体和为 k，只有整个数组这一种取法 ----------
        check(new int[]{2, 3, 5}, 10, 1);
    }

    /** des: 两种解法跑同一组用例并与期望值比对，防止哈希表写法在边界上跑偏 */
    private static void check(int[] nums, int k, int expected) {
        SubarraySum solution = new SubarraySum();
        int fast = solution.subarraySum(nums, k);
        int slow = solution.subarraySumByBruteForce(nums, k);

        boolean pass = fast == expected && slow == expected;
        System.out.printf("nums = %s, k = %d%n", java.util.Arrays.toString(nums), k);
        System.out.printf("  期望值        : %d%n", expected);
        System.out.printf("  前缀和+哈希表 : %d%s%n", fast, fast == expected ? "  ✅" : "  ❌");
        System.out.printf("  暴力枚举      : %d%s%n", slow, slow == expected ? "  ✅" : "  ❌");
        System.out.println(pass ? "  => 通过" : "  => 失败");
        System.out.println();
    }
}
