package org.lwl.leetcode;

import java.util.Arrays;

/**
 * LeetCode 283 - 移动零（提交时将类名改为 Solution）
 * <p>
 * 题目：给定一个数组 nums，编写一个函数将所有 0 移动到数组的末尾，同时保持非零元素的相对顺序。
 * 请注意，必须在不复制数组的情况下原地对数组进行操作。
 * <p>
 * 关键理解：把题面拆成三条硬约束，解法方向基本就被框定了。
 * 1. 「把所有 0 移到末尾」——0 是唯一被搬动的元素，非零元素只是「换个位置站队」。
 *    也就是说，搬家的本质不是「把 0 往后扔」，而是「把非零元素往前挤」。
 *    这个视角的转换是本题的第一个关键：盯着 0 看会写出 O(n²)，盯着非零元素看才会写出 O(n)。
 * 2. 「保持非零元素的相对顺序」——这是稳定性要求，它直接排除了一个很顺手的写法。
 *    本包 RemoveElement（LeetCode 27）里的首尾双指针「用尾部元素覆盖头部」正是最快、写入最少的做法，
 *    但它会把末尾元素甩到前面，顺序被打乱，因此在这里不能用。
 *    这也是本题与 27 题最本质的区别：同样是原地删元素，一个允许乱序、一个要求保序，
 *    结果一个能用首尾指针、一个只能用快慢指针。约束差一句话，解法差一个量级。
 * 3. 「不复制数组、原地操作」——禁止开新数组，额外空间必须是 O(1)（若干下标变量和临时变量，与 n 无关）。
 *    注意这条约束禁的是「复制整个数组」，用两三个 int 变量是允许的，
 *    很多人会把它误读成「一个变量都不许加」而白白绕远路。
 * <p>
 * 为什么直觉写法会掉进 O(n²)：
 * 最朴素的想法是「从左往右扫，遇到 0 就把它和后面所有元素整体交换/左移一位」。
 * 但每次左移都要搬动后面的一整串元素，最坏情况（如 {0,0,...,0,1,2,...,n}）总搬动次数是 O(n²)。
 * 数组的插入删除之所以贵，就是因为「腾位置」需要整体搬移；而本题的破解点在于——
 * 我们根本不需要真的去「腾位置」，只需要把非零元素按序写到前面，剩下的位置天然就是 0。
 * <p>
 * 核心思路：快慢指针（方法一，推荐，O(n) / O(1)）
 * <p>
 * 设置两个指针：
 * - slow：指向「下一个非零元素应该落脚的坑位」，也可以理解成「已归位的非零元素个数」；
 * - fast：从左到右扫描整个数组，负责找非零元素。
 * <p>
 * fast 每遇到一个非零元素，就把它写到 nums[slow] 并让 slow 前进一格；遇到 0 则什么都不做。
 * 扫描结束后，slow 恰好等于非零元素的个数，于是 [0, slow) 是保序的非零序列，
 * 把 [slow, n) 整段填 0 即可。
 * <p>
 * 这里有第二个值得想清楚的点：为什么可以「直接覆盖」nums[slow]，不怕把数据冲掉？
 * 因为慢指针永远不越过快指针（slow <= fast 恒成立），被覆盖的位置要么是已经读过的旧数据，
 * 要么就是快指针自己当前所在的位置（此时是自己写自己，即空操作）。
 * 换句话说，快的那个指针已经把要用的信息「抄」在手里了，旧位置作废是安全的。
 * 这也是「原地」能够成立的根本原因——不是不破坏数据，而是被破坏的数据已经没用了。
 * <p>
 * 方法二：快慢指针 + 交换（少一次收尾循环，写入次数视数据分布而定）
 * 遇到非零元素时不再覆盖，而是交换 nums[slow] 与 nums[fast]。
 * 好处是循环结束时 0 已经被顺带换到了后面，不需要再补一次填零的循环；
 * 代价是每次交换要写两个位置，零越多交换越多。
 * 两种写法的取舍可以这样记：
 * - 零很少时，覆盖法只在末尾补一小段 0，整体写入更少（推荐）；
 * - 零很多时，交换法的收尾成本为零，反而更省。
 * 复杂度两者都是 O(n) / O(1)，实际工程里选哪个差别极小，理解它们的差异比背下来更有价值。
 * <p>
 * 时间复杂度 O(n)：快指针恰好把数组扫一遍，每个元素只被检查一次；收尾填零最多再走 n 步。
 * 常数上有两次线性遍历，但仍是 O(n)。
 * 空间复杂度 O(1)：只用 slow、fast 两个下标和（方法二里）一个交换用临时变量，不随 n 增长。
 * 这正是题目「不复制数组」想要的结果。
 * <p>
 * 举一反三：这道题是「快慢指针」这个模式的入门样板，值得记住的是它的骨架而不是答案本身。
 * 快慢指针的通用骨架是：fast 负责「读」，slow 负责「写」，两者之间天然形成一条分界线——
 * 分界线左边是已处理好的结果，右边是尚未处理的原始数据。
 * 一旦意识到 slow 就是「结果的长度」，一大类题都能套进这个框架：
 * - LeetCode 26 删除排序数组重复项：非零判定换成「与前一个不同」（见本包 RemoveDuplicates）；
 * - LeetCode 27 移除元素：非零判定换成「不等于 val」，但若要保序也只能用快慢指针（见本包 RemoveElement）；
 * - LeetCode 80 删除重复项 II：再加一个计数器，允许每个元素出现两次；
 * - LeetCode 75 颜色分类：快慢指针升级成三指针，一次遍历把三类元素分区。
 * <p>
 * 更值得注意的是本题揭示的一条通用判断法：遇到「原地操作数组」的题，先问两句——
 * 「顺序能不能打乱？」「能不能开新数组？」
 * 这两个问题的答案组合，基本决定了解法形态：
 * - 可以乱序 + 要求 O(1) 空间 → 首尾双指针（写入最少）；
 * - 必须保序 + 要求 O(1) 空间 → 快慢指针（本题）；
 * - 允许额外空间 → 直接开新数组装非零再补零，最省脑力（本题不允许，但换个场景就该选它）。
 * 先看清约束再动手，比记住十道题的答案都有用。
 */
public class MoveZeroes {

    // ============ 方法一：快慢指针覆盖 + 末尾补零（推荐，O(n) / O(1)） ============

    /**
     * des: fast 扫描找非零元素，slow 指向下一个落脚点，扫完后把剩余位置统一填 0
     */
    public void moveZeroes(int[] nums) {
        if (nums == null || nums.length == 0) {
            // 空数组无事可做，同时也避免后面访问 nums[0] 越界
            return;
        }

        // slow 既是「下一个非零元素的落脚下标」，也是「已归位的非零元素个数」
        int slow = 0;

        for (int fast = 0; fast < nums.length; fast++) {
            if (nums[fast] != 0) {
                // 只处理非零元素：按它们在原数组中的先后顺序依次写到前面，顺序自然得以保持
                // slow <= fast 恒成立，所以此处是「写到已读过的位置」，不会丢数据
                nums[slow] = nums[fast];
                slow++;
            }
            // 遇到 0 直接跳过：0 不需要被搬走，它「留在原地」就等于已经去了后面
        }

        // 非零元素全部就位后，[slow, n) 这一段自动就是需要清零的尾部
        while (slow < nums.length) {
            nums[slow] = 0;
            slow++;
        }
    }

    // ============ 方法二：快慢指针 + 交换（免去收尾循环） ============

    /**
     * des: 遇到非零元素就与 slow 位置交换，0 被顺带换到后面，因此不需要单独补零
     * <p>
     * 与方法一的差别只在「怎么写」：这里是交换（写 2 个位置），方法一是覆盖 + 末尾补零。
     * 数组里零越多，这个方法越划算；零越少，方法一越划算。两者复杂度完全相同。
     */
    public void moveZeroesBySwap(int[] nums) {
        if (nums == null || nums.length == 0) {
            return;
        }

        int slow = 0;

        for (int fast = 0; fast < nums.length; fast++) {
            if (nums[fast] != 0) {
                // 尚未出现 0 时 slow == fast，交换是自己和自己换，纯属浪费，跳过
                if (slow != fast) {
                    int tmp = nums[slow];
                    nums[slow] = nums[fast];
                    nums[fast] = tmp;
                }
                slow++;
            }
        }
        // 循环结束时 0 已被交换到尾部，无需补零
    }

    // ============ 方法三：遇到 0 就整体左移（O(n²)，用于说明直觉写法为何不可取） ============

    /**
     * des: 从左往右找 0，找到后把其后的元素整体左移一位，再把 0 放到末尾
     * <p>
     * 结果正确，但每遇到一个 0 都要搬动后面的一整串元素，
     * 面对 {0,0,...,0,1,2,...,m} 这类输入总搬动次数约 n²/2，即 O(n²)。
     * <p>
     * 保留它是为了对照：方法一之所以是 O(n)，靠的不是「搬得更快」，而是「根本不搬」——
     * 非零元素只写一次到最终位置，0 则一次都不写（方法一）或只换一次（方法二）。
     * 想清楚「哪些写操作是可以省掉的」，往往就是原地算法优化的全部。
     */
    public void moveZeroesByShift(int[] nums) {
        if (nums == null || nums.length == 0) {
            return;
        }

        // last 表示「尚未确定的有效区间的末尾下标」，随着 0 被推到后面而不断前移
        int last = nums.length - 1;

        for (int i = 0; i <= last; i++) {
            if (nums[i] == 0) {
                // 把 i 之后的元素整体左移一位，空出的末尾放 0
                for (int j = i; j < last; j++) {
                    nums[j] = nums[j + 1];
                }
                nums[last] = 0;
                // 末尾已被 0 占据，有效区间缩短一格
                last--;
                // 左移后 i 位置换来了新元素，必须重新判断，因此回退一格
                i--;
            }
        }
    }

    // ============ 测试用例 ============

    public static void main(String[] args) {
        // ---------- 用例 1：官方示例，0 与非零元素交替出现 ----------
        check(new int[]{0, 1, 0, 3, 12}, new int[]{1, 3, 12, 0, 0});

        // ---------- 用例 2：官方示例，只有一个 0 ----------
        check(new int[]{0}, new int[]{0});

        // ---------- 用例 3：空数组，验证不会越界 ----------
        check(new int[]{}, new int[]{});

        // ---------- 用例 4：没有 0，验证数组应原样不动 ----------
        check(new int[]{1, 2, 3}, new int[]{1, 2, 3});

        // ---------- 用例 5：全是 0，验证补零循环不会越界 ----------
        check(new int[]{0, 0, 0}, new int[]{0, 0, 0});

        // ---------- 用例 6：0 全部集中在开头，是最需要整体前移的情形 ----------
        check(new int[]{0, 0, 0, 1, 2}, new int[]{1, 2, 0, 0, 0});

        // ---------- 用例 7：0 全部集中在末尾，验证非零元素不会被多余的搬动打乱 ----------
        check(new int[]{1, 2, 3, 0, 0}, new int[]{1, 2, 3, 0, 0});

        // ---------- 用例 8：0 夹在中间，验证相对顺序的保持 ----------
        check(new int[]{1, 0, 2, 0, 3}, new int[]{1, 2, 3, 0, 0});

        // ---------- 用例 9：含负数，验证「非零」判定对负数同样成立 ----------
        check(new int[]{-1, 0, -2, 0, 0, -3}, new int[]{-1, -2, -3, 0, 0, 0});

        // ---------- 用例 10：长度为 2 的两种情形，验证 slow != fast 的跳过分支 ----------
        check(new int[]{0, 1}, new int[]{1, 0});
        check(new int[]{1, 0}, new int[]{1, 0});

        // ---------- 用例 11：较长的零散分布，验证归位后仍严格保序 ----------
        check(new int[]{4, 0, 5, 0, 0, 6, 7}, new int[]{4, 5, 6, 7, 0, 0, 0});

        // ---------- 用例 12：含 Integer 边界值，验证只是比较 0、不涉及算术运算，无溢出风险 ----------
        check(new int[]{Integer.MIN_VALUE, 0, Integer.MAX_VALUE},
                new int[]{Integer.MIN_VALUE, Integer.MAX_VALUE, 0});

        // ---------- 用例 13：最坏输入之一，方法三在此退化为 O(n²) ----------
        check(new int[]{0, 0, 0, 0, 0, 1, 2, 3, 4, 5},
                new int[]{1, 2, 3, 4, 5, 0, 0, 0, 0, 0});
    }

    /** des: 三种解法各跑一份独立的数组副本（原地操作会改写入参，必须隔离），再与期望数组整段比对 */
    private static void check(int[] nums, int[] expected) {
        MoveZeroes solution = new MoveZeroes();

        // 原地操作会破坏入参，因此每次调用前都要新拷一份，保证三种解法面对同一份初始数据
        int[] a1 = Arrays.copyOf(nums, nums.length);
        int[] a2 = Arrays.copyOf(nums, nums.length);
        int[] a3 = Arrays.copyOf(nums, nums.length);

        solution.moveZeroes(a1);
        solution.moveZeroesBySwap(a2);
        solution.moveZeroesByShift(a3);

        boolean pass = Arrays.equals(a1, expected)
                && Arrays.equals(a2, expected)
                && Arrays.equals(a3, expected);

        System.out.printf("nums = %s%n", Arrays.toString(nums));
        System.out.printf("  期望值       : %s%n", Arrays.toString(expected));
        System.out.printf("  快慢指针覆盖 : %s%s%n", Arrays.toString(a1), Arrays.equals(a1, expected) ? "  ✅" : "  ❌");
        System.out.printf("  快慢指针交换 : %s%s%n", Arrays.toString(a2), Arrays.equals(a2, expected) ? "  ✅" : "  ❌");
        System.out.printf("  逐个左移     : %s%s%n", Arrays.toString(a3), Arrays.equals(a3, expected) ? "  ✅" : "  ❌");
        System.out.println(pass ? "  => 通过" : "  => 失败");
        System.out.println();
    }
}
